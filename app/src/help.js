export const topicById = (id) => TOPICS.find((t) => t.id === id);

// Алфавитный предметный указатель: ключевое слово (K) → темы
export function buildIndex() {
  const map = new Map();
  for (const t of TOPICS) {
    for (const k of t.keywords ?? []) {
      if (!map.has(k)) map.set(k, []);
      map.get(k).push(t.id);
    }
  }
  return [...map.entries()].sort((a, b) => a[0].localeCompare(b[0], 'ru'));
}

export const topicsByKeywords = (kws) => TOPICS.filter((t) => kws.some((k) => (t.keywords ?? []).includes(k)));
export const topicsByAlink = (key) => TOPICS.filter((t) => (t.alinks ?? []).includes(key));
